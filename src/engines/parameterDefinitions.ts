export function getReferenceRange(
  param: ParameterConfig,
  sampleType: SampleType
): [number, number] {
  if (sampleType === 'Venosa') return param.refVenosa;
  if (sampleType === 'Capilar') return param.refCapilar;
  return param.refArterial;
}

export function evaluateFlag(
  key: ParameterKey,
  value: number | null | undefined,
  sampleType: SampleType,
  paramsConfig: Record<ParameterKey, ParameterConfig>
): AbnormalityFlag {
  if (value === null || value === undefined || Number.isNaN(value)) return 'ND';
  const cfg = paramsConfig[key];
  if (!cfg) return 'NORMAL';

  if (cfg.criticalLow !== undefined && value <= cfg.criticalLow) {
    // Avoid marking Venosa pO2 as critical arterial hypoxemia
    if (!(key === 'pO2' && sampleType === 'Venosa') && !(key === 'sO2' && sampleType === 'Venosa') && !(key === 'FO2Hb' && sampleType === 'Venosa')) {
      return 'CRITICAL_LOW';
    }
  }
  if (cfg.criticalHigh !== undefined && value >= cfg.criticalHigh) {
    return 'CRITICAL_HIGH';
  }

  const [low, high] = getReferenceRange(cfg, sampleType);
  if (value < low) return 'LOW';
  if (value > high) return 'HIGH';
  return 'NORMAL';
}
